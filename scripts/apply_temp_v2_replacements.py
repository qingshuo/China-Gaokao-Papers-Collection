def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def planned_replacements(
    rows: list[dict[str, str]],
) -> list[tuple[dict[str, str], dict[str, str], Path, Path, Path]]:
    by_id = {row["record_id"]: row for row in rows}
    plans = []
    for record_id, decision in REPLACEMENTS.items():
        row = by_id.get(record_id)
        if row is None:
            raise ValueError(f"replacement record not found: {record_id}")
        source = ROOT / decision["source"]
        current_destination = ROOT / row["local_path"]
        destination = ROOT / decision.get("local_path", row["local_path"])
        if not source.is_file() or not current_destination.is_file():
            raise FileNotFoundError(f"replacement files missing for {record_id}")
        current_hash = sha256(current_destination)
        if row.get("sha256") == decision["new_sha256"] and current_hash == decision["new_sha256"]:
            continue
        if row.get("sha256") != decision["old_sha256"] or current_hash != decision["old_sha256"]:
            raise ValueError(f"unexpected current hash for {record_id}")
        if sha256(source) != decision["new_sha256"]:
            raise ValueError(f"unexpected candidate hash for {record_id}")
        if destination != current_destination and destination.exists():
            raise FileExistsError(f"new destination already exists for {record_id}: {destination}")
        plans.append((row, decision, source, current_destination, destination))
    return plans


def planned_additions(rows: list[dict[str, str]]) -> list[tuple[str, dict[str, str], Path, Path]]:
    """Return only hash-locked new records that do not yet exist locally."""
    by_id = {row["record_id"]: row for row in rows}
    existing_hashes = {row.get("sha256") for row in rows if row.get("sha256")}
    plans = []
    for record_id, decision in ADDITIONS.items():
        source = ROOT / decision["source"]
        destination = ROOT / decision["local_path"]
        if record_id in by_id:
            row = by_id[record_id]
            if (
                row.get("sha256") == decision["sha256"]
                and destination.is_file()
                and sha256(destination) == decision["sha256"]
            ):
                continue
            raise ValueError(f"unexpected existing record for {record_id}")
        if decision["sha256"] in existing_hashes:
            raise ValueError(f"addition hash already catalogued for {record_id}")
        if not source.is_file() or sha256(source) != decision["sha256"]:
            raise ValueError(f"unexpected candidate hash for {record_id}")
        if destination.exists():
            raise FileExistsError(f"addition destination already exists for {record_id}: {destination}")
        plans.append((record_id, decision, source, destination))
    return plans


def mark_reviewed_replacements_verified(rows: list[dict[str, str]]) -> int:
    """Mark only already-applied, hash-locked review decisions as verified.

    ``verified`` records the repository's content and layout review.  It does
    not claim that a local upload has an official source or a redistribution
    licence; those remain in their separate catalogue fields.
    """
    by_id = {row["record_id"]: row for row in rows}
    updates = 0
    for record_id, decision in REPLACEMENTS.items():
        row = by_id[record_id]
        destination = ROOT / decision.get("local_path", row["local_path"])
        if (
            row.get("sha256") == decision["new_sha256"]
            and destination.is_file()
            and sha256(destination) == decision["new_sha256"]
            and row.get("status") != "verified"
        ):
            row["status"] = "verified"
            updates += 1
    return updates


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="replace reviewed files and update the catalog")
    args = parser.parse_args()
    with CATALOG.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        fieldnames = list(reader.fieldnames or [])
        rows = list(reader)
    plans = planned_replacements(rows)
    additions = planned_additions(rows)
    for row, _, source, _, destination in plans:
        print(f"{row['record_id']}: {source.relative_to(ROOT)} -> {destination.relative_to(ROOT)}")
    for _, decision, source, destination in additions:
        print(f"{source.relative_to(ROOT)} -> {destination.relative_to(ROOT)}")
    print(f"replacements={len(plans)} additions={len(additions)} mode={'apply' if args.apply else 'dry-run'}")
    if not args.apply:
        return 0
    for row, decision, source, current_destination, destination in plans:
        destination.parent.mkdir(parents=True, exist_ok=True)
        staged = destination.with_name(f".{destination.name}.temp-v2")
        shutil.copy2(source, staged)
        staged.replace(destination)
        if current_destination != destination:
            current_destination.unlink()
        row["sha256"] = decision["new_sha256"]
        row["title"] = decision["title"]
        row["paper_type"] = decision["paper_type"]
        row["region"] = decision.get("region", row["region"])
        row["local_path"] = decision.get("local_path", row["local_path"])
        row["status"] = "verified"
        row["source_url"] = f"local://{quote(decision['source'], safe='/')}"
        row["source_type"] = decision.get("source_type", row["source_type"])
        row["license_status"] = decision.get("license_status", row["license_status"])
        if decision["note"] not in row["notes"]:
            row["notes"] = f"{row['notes']}；{decision['note']}"
    for record_id, decision, source, destination in additions:
        destination.parent.mkdir(parents=True, exist_ok=True)
        staged = destination.with_name(f".{destination.name}.temp-v2")
        shutil.copy2(source, staged)
        staged.replace(destination)
        rows.append({
            "record_id": record_id,
            "year": decision["year"], "region": decision["region"], "paper_type": decision["paper_type"],
            "subject": decision["subject"], "title": decision["title"],
            "source_url": f"local://{quote(decision['source'], safe='/')}",
            "source_type": "local-upload", "license_status": "unknown", "availability": "local",
            "status": "verified", "local_path": decision["local_path"], "sha256": decision["sha256"],
            "notes": decision["note"], "material_type": "完整试卷",
        })
    verified_updates = mark_reviewed_replacements_verified(rows)
    if verified_updates:
        print(f"marked_verified={verified_updates}")
    with tempfile.NamedTemporaryFile("w", newline="", encoding="utf-8", dir=CATALOG.parent, delete=False) as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
        temporary = Path(handle.name)
    temporary.replace(CATALOG)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
